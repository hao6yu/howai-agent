create function public.finish_automation_delivery(
  p_delivery_id uuid,
  p_outcome text,
  p_summary jsonb
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.jwt() ->> 'role') is distinct from 'service_role' then
    raise exception 'service role required' using errcode = '42501';
  end if;
  if p_outcome not in ('sent', 'partial', 'no_devices', 'failed')
    or p_summary is null or jsonb_typeof(p_summary) <> 'object' then
    raise exception 'invalid completion values' using errcode = '22023';
  end if;

  update public.automation_run_deliveries
  set
    status = p_outcome,
    provider_summary = p_summary,
    sent_at = case
      when p_outcome in ('sent', 'partial') then pg_catalog.now()
      else null
    end,
    completed_at = pg_catalog.now(),
    lease_expires_at = null,
    updated_at = pg_catalog.now()
  where id = p_delivery_id
    and status = 'processing';

  if found then return true; end if;

  return exists (
    select 1
    from public.automation_run_deliveries
    where id = p_delivery_id
      and status in ('sent', 'partial', 'no_devices', 'failed')
  );
end;
$$;

