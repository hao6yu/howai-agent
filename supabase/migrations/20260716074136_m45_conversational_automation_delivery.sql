    update public.automation_run_deliveries d
    set
      status = 'processing',
      attempt_count = d.attempt_count + 1,
      lease_expires_at = pg_catalog.now() + interval '2 minutes',
      updated_at = pg_catalog.now()
    from candidates c
    where d.id = c.id
    returning d.*
  )
  select
    claimed.id,
    claimed.automation_run_id,
    claimed.user_id,
    claimed.conversation_id,
    claimed.message_id,
    claimed.title,
    claimed.preview,
    claimed.attempt_count
