-- Reuse the existing scheduler secret. It authenticates only internal Cron
-- dispatchers and remains in Vault/Edge Function secrets, never in git.
select cron.schedule(
  'howai-dispatch-automations',
  '* * * * *',
  $schedule$
    select net.http_post(
      url := secrets.project_url || '/functions/v1/dispatch-automations',
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'x-howai-cron-secret', secrets.dispatch_secret
      ),
      body := '{}'::jsonb,
      timeout_milliseconds := 150000
    )
    from (
      select
        max(decrypted_secret) filter (
          where name = 'howai_project_url'
        ) as project_url,
        max(decrypted_secret) filter (
          where name = 'howai_reminder_dispatch_secret'
        ) as dispatch_secret
      from vault.decrypted_secrets
    ) secrets
    where secrets.project_url is not null
      and secrets.dispatch_secret is not null;
  $schedule$
);
