-- M4.5 conversational Automation delivery.
--
-- One shared Cron tick creates durable occurrences, workers claim them with
-- short leases, and completion atomically appends the verified assistant
-- message before a separate, retryable push-delivery record is created.

alter table public.automation_runs
  add column conversation_id uuid
    references public.conversations(id) on delete set null,
  add column conversation_message_id uuid unique
    references public.messages(id) on delete set null;

create index automation_runs_conversation_idx
  on public.automation_runs (conversation_id, created_at desc)
  where conversation_id is not null;

create table public.automation_run_deliveries (
  id uuid primary key default gen_random_uuid(),
  automation_run_id uuid not null unique
    references public.automation_runs(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id uuid not null
    references public.conversations(id) on delete cascade,
  message_id uuid not null unique
    references public.messages(id) on delete cascade,
  title text not null,
  preview text not null,
  status text not null default 'pending',
  attempt_count smallint not null default 0,
  available_at timestamptz not null default now(),
  lease_expires_at timestamptz,
  provider_summary jsonb not null default '{}'::jsonb,
  sent_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint automation_run_deliveries_title_length
    check (char_length(btrim(title)) between 1 and 200),
  constraint automation_run_deliveries_preview_length
    check (char_length(btrim(preview)) between 1 and 500),
  constraint automation_run_deliveries_status_check
    check (status in (
      'pending', 'processing', 'retrying',
      'sent', 'partial', 'no_devices', 'failed'
    )),
  constraint automation_run_deliveries_attempt_count_check
    check (attempt_count between 0 and 10),
  constraint automation_run_deliveries_summary_object
    check (jsonb_typeof(provider_summary) = 'object'),
  constraint automation_run_deliveries_completion_state
    check (
      (status in ('sent', 'partial', 'no_devices', 'failed'))
      = (completed_at is not null)
    ),
  constraint automation_run_deliveries_updated_order
    check (updated_at >= created_at)
);

alter table public.automation_run_deliveries enable row level security;
revoke all on public.automation_run_deliveries
  from public, anon, authenticated;
grant all on public.automation_run_deliveries to service_role;

create index automation_run_deliveries_ready_idx
