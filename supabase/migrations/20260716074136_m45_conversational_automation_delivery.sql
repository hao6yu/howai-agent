create function public.claim_due_automation_runs(
  p_limit integer default 4
)
returns table (
  run_id uuid,
  automation_id uuid,
  user_id uuid,
  conversation_id uuid,
  automation_version integer,
  scheduled_for timestamptz,
  attempt_number smallint,
  template_snapshot jsonb
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_mode text;
  v_market_enabled boolean;
begin
  if (select auth.jwt() ->> 'role') is distinct from 'service_role' then
    raise exception 'service role required' using errcode = '42501';
  end if;
  if p_limit < 1 or p_limit > 10 then
    raise exception 'p_limit must be between 1 and 10'
      using errcode = '22023';
  end if;

  select case
    when count(*) = 3
      and bool_and(enabled)
      and bool_and(payload ->> 'mode' in ('internal', 'full'))
    then case
      when bool_and(payload ->> 'mode' = 'full') then 'full'
      else 'internal'
    end
    else null
  end
  into v_mode
  from public.feature_flags
  where key in (
    'automations',
    'automation_web_retrieval',
    'automation_validation'
  );

  if v_mode is null then
    return;
  end if;

  select coalesce(enabled, false)
    and payload ->> 'mode' in ('internal', 'full')
  into v_market_enabled
  from public.feature_flags
  where key = 'automation_market_data';

  v_market_enabled := coalesce(v_market_enabled, false);

  with due as materialized (
    select a.*
    from public.automations a
    where a.status = 'active'
      and a.next_run_at <= pg_catalog.now()
      and (a.kind <> 'market_briefing' or v_market_enabled)
      and exists (
        select 1
        from public.app_entitlements e
        where e.user_id = a.user_id
          and e.tier = 'paid'
          and (e.expires_at is null or e.expires_at > pg_catalog.now())
          and (v_mode = 'full' or e.model_policy_canary = true)
      )
      and not exists (
        select 1
        from public.automation_runs existing
        where existing.automation_id = a.id
          and existing.scheduled_for = a.next_run_at
      )
    order by a.next_run_at, a.id
    limit p_limit
    for update of a skip locked
  )
  insert into public.automation_runs (
    automation_id,
    user_id,
    conversation_id,
    automation_version,
    scheduled_for,
    trigger_type,
    template_snapshot
  )
  select
    due.id,
    due.user_id,
    due.conversation_id,
    due.version,
    due.next_run_at,
    'scheduled',
    jsonb_build_object(
      'automation_id', due.id,
      'kind', due.kind,
      'title', due.title,
      'timezone', due.timezone,
      'start_local', due.start_local,
      'schedule_rule', due.schedule_rule,
      'config', due.config,
      'source_policy', due.source_policy,
      'delivery_preferences', due.delivery_preferences
    )
  from due
  on conflict on constraint automation_runs_occurrence_unique do nothing;

  return query
  with candidates as materialized (
    select r.id
    from public.automation_runs r
    where (
      (r.status = 'queued' and r.available_at <= pg_catalog.now())
      or (
        r.status in ('running', 'verifying')
        and r.lease_expires_at <= pg_catalog.now()
      )
    )
      and r.attempt_count < 10
    order by r.available_at, r.created_at, r.id
    limit p_limit
    for update of r skip locked
  ), claimed as (
    update public.automation_runs r
    set
      status = 'running',
      attempt_count = r.attempt_count + 1,
      lease_expires_at = pg_catalog.now() + interval '5 minutes',
      started_at = coalesce(r.started_at, pg_catalog.now()),
      updated_at = pg_catalog.now()
    from candidates c
    where r.id = c.id
    returning r.*
  )
  select
    claimed.id,
    claimed.automation_id,
    claimed.user_id,
    claimed.conversation_id,
    claimed.automation_version,
    claimed.scheduled_for,
    claimed.attempt_count,
    claimed.template_snapshot
  from claimed
  order by claimed.scheduled_for, claimed.id;
end;
$$;

