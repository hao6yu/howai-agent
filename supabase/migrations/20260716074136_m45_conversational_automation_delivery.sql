create function public.retry_automation_run(
  p_run_id uuid,
  p_delay_seconds integer,
  p_error_code text,
  p_error_message text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.jwt() ->> 'role') is distinct from 'service_role' then
    raise exception 'service role required' using errcode = '42501';
  end if;
  if p_delay_seconds < 5 or p_delay_seconds > 3600
    or p_error_code is null or char_length(p_error_code) > 100
    or p_error_message is null or char_length(p_error_message) > 500 then
    raise exception 'invalid retry values' using errcode = '22023';
  end if;

  update public.automation_runs
  set
    status = 'queued',
    available_at = pg_catalog.now()
      + pg_catalog.make_interval(secs => p_delay_seconds),
    lease_expires_at = null,
    error_code = p_error_code,
    error_message = p_error_message,
    updated_at = pg_catalog.now()
  where id = p_run_id
    and status in ('running', 'verifying');

  return found;
end;
$$;

