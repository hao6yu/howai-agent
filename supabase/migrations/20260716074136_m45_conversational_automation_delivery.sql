create index automation_run_deliveries_user_idx
  on public.automation_run_deliveries (user_id, created_at desc);
create index automation_run_deliveries_conversation_idx
  on public.automation_run_deliveries (conversation_id, created_at desc);

create trigger set_automation_run_delivery_updated_at
